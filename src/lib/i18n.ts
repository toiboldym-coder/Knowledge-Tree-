export function readStoredLang(): Lang | null {
  try {
    const raw = localStorage.getItem(LANG_STORAGE);
    if (raw === "en" || raw === "ru") return raw;
  } catch {
    /* ignore */
  }
  return null;
}

export function storeLang(lang: Lang) {
  try {
    localStorage.setItem(LANG_STORAGE, lang);
  } catch {
    /* ignore */
  }
}
